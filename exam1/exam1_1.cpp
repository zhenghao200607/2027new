//
// 输入：5 8 2 10 7 15 13 11 20 18
// 输出：2 5 7 8 10 11 13 15 18 20      （升序，从小到大）
//
// 编译运行：VS Code 里按 Ctrl+Shift+B
// 要求：零编译警告（run.cmd 已经开了 -Wall -Wextra）
// ============================================================

#include <iostream>

int main() {
    const int N = 10;
    int a[N];

    for (int i = 0;i < N; i++) {
        std::cin >> a[i];
    }

    for (int i = 0; i < N - 1; i++) {          // 几轮？
        for (int j = 0; j < N - 1 - i  ; j++) {      // 比到第几个？
            if (a[j] > a[j + 1]) {         // 什么条件交换？
                int t = a[j];
                a[j] = a[j + 1];
                a[j + 1] = t;
            }
        }
    }

    for (int i = 0; i < N; i++) {
        std::cout << a[i] << " ";
    }
    // ---- 第 1 步：准备一个能装 10 个整数的数组 ----
    // 数组就是"一排格子"，编号从 0 开始，所以 10 个格子的编号是 0 ~ 9
    // 写法（把下面两行取消注释、按需要修改变量名）：
    //     const int N = 10;    // 一共几个数
    //     int a[N];            // a[0] 到 a[9]
    // 注意：声明了却不使用会报 unused variable 警告，所以要和后面的代码一起写。


    // ---- 第 2 步：把 10 个数从键盘读进数组 ----
    // 用 for 循环：i 从 0 数到 9，每次读一个数放进 a[i]
    // 提示：读入用 std::cin >> 变量;


    // ---- 第 3 步：排序 ← 这道题的核心，也是面试必问的地方 ----
    // 用「冒泡排序」：
    //   第 1 轮：从左到右，相邻两个比大小，前面比后面大就交换。
    //            走完这一轮，最大的数会被"冒"到最后一个格子。
    //   第 2 轮：同样操作，但最后一个格子已经确定了，不用再动。
    //   第 3 轮：倒数第二个也确定了……
    //   一直重复，直到全部有序。
    //
    // 【自己推一下再动笔】：
    //   · 一共需要几轮？（10 个数，每轮定一个，想想最后一个还用不用管）
    //   · 第 i 轮里，内层循环要比较到第几个格子？为什么每轮能少比一次？
    //
    // 交换两个数的写法（想清楚为什么必须借临时变量 t）：
    //     int t = a[j];
    //     a[j] = a[j + 1];
    //     a[j + 1] = t;
    //
    // 整体是「两层 for 循环嵌套」：外层管轮数，内层管这一轮里比较到哪


    // ---- 第 4 步：输出 ----
    // 再来一个 for 循环，把 a[0] ~ a[9] 依次打印
    // 每个数后面跟一个空格，结果就会是 "2 5 7 8 ..."

    return 0;
}
