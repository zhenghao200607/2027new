// ============================================================
//
// 【本题要理解的三个概念】
//
// ① 封装：private 与 public
//      class Car {
//      private:                    // 私有：只有类内部的函数能碰
//          std::string color;
//          int number;
//      public:                     // 公有：外面（main）也能调用
//          ...
//      };
//
//    ⚠ class 的成员默认是 private，所以必须显式写 public: 才能从 main 访问
//      （对比第 2 题的 struct，成员默认是 public —— 这是 class 和 struct 最本质的区别，
//        也是面试常考的点）
//
// ② 构造函数：名字和类名一样，没有返回类型，创建对象时自动被调用
//
//      Car(std::string c, int n) {
//          color = c;
//          number = n;
//      }
//
//    更地道的写法是「初始化列表」（可选项，写了显得专业）：
//      Car(std::string c, int n) : color(c), number(n) {}
//
// ③ 析构函数：名字是 ~类名，没有参数没有返回类型，对象销毁时自动被调用
//
//      ~Car() {
//          // 可以在这里打印点什么
//      }
//
//    ⚠ 为什么第 3 题要考析构函数？因为要让你亲眼看到「对象什么时候死」。
//      在析构函数里打印一句话，运行后你会看到它在 main 结束前自己跑了一遍。
//      这和面试题「析构函数什么时候调用」直接对应。
//
// ============================================================
//
// 【蓝图】
//
//   #include <iostream>
//   #include <string>          ← 用 std::string 必须包含这个头文件
//
//   class Car {
//   private:
//       std::string color;
//       int number;
//
//   public:
//       // 构造函数
//       Car(std::string c, int n) { ... }
//
//       // 析构函数
//       ~Car() { ... }
//
//       // display：输出这辆车的信息
//       void display() { ... }
//   };
//
//   int main() {
//       Car car1("红色", 1001);     // 创建第 1 辆车，构造函数自动被调用
//       Car car2("蓝色", 1002);     // 创建第 2 辆车
//       car1.display();            // 用「.」调用，因为 car1 是对象本身
//       car2.display();
//       return 0;
//   }
//
// ============================================================
//
// 【自己动手填的部分】
//
//   · 构造函数体：把参数 c 和 n 分别存进 color 和 number
