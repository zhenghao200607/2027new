// ============================================================
// 考核一 · 第 2 题
//
// 输入：张三 / 123 / 90.5
// 输出：
//   姓名：张三
//   学号：123
//   成绩：90.5
//
// 编译运行：VS Code 里按 Ctrl+Shift+B
// 要求：零编译警告         // ← 这个分号最容易漏！// ============================================================
//
// 【题目要求原文】
//   定义一个结构体 Student，包含：
//     name（字符数组，长度 50）、id（整数）、score（浮点数）
//   编写两个函数：
//     input()：通过指针接收结构体，从键盘输入学生信息
//     display()：通过指针接收结构体，输出学生信息
//   要使用 -> 运算符输入和输出
//   在 main() 中：动态创建一个 Student 结构体变量，调用 input()，调用 display()
//
// ============================================================
//
// 【蓝图】照着敲，不要复制粘贴——指针这东西手敲一遍才算真过一遍脑子
//
// ① 定义结构体（放在 #include 之后、所有函数之前）
//
//      struct Student {
//          char  name[50];    // 字符数组，长度 50
//          int   id;          // 学号
//          float score;       // 成绩
//      };
//
//    ⚠ 结尾那个分号千万别漏！结构体定义也是一条完整语句。
//    ⚠ 为什么题目要求用 char 数组而不是 std::string？因为考点就是"数组"，
//      而且 char name[50] 正好能装下中文（UTF-8 一个汉字占 3 字节，50 字节能装 16 个汉字）。
//
// ② input 函数：用「指针」接收结构体
//
//      void input(Student* p) { ... }
//
//    参数写 Student* p，意思是"p 是一个指针，指向一个 Student"。
//
// ③ display 函数：同样用指针接收
//
//      void display(Student* p) { ... }
//
// ④ main 里：动态创建 + 调用 + 释放
//
//      int main() {
//          Student* p = new Student;   // 动态创建
//          input(p);
//          display(p);
//          delete p;                   // 释放
//          return 0;
//      }
//
// ============================================================
//
// 【必须搞懂的核心】-> 到底是什么？
//
//   假设有一个指针 p，指向一个 Student。想访问它指向的那个学生的 name 字段：
//
//      (*p).name        ← 先解引用拿到对象，再取成员。合法，但写起来很啰嗦
//      p->name          ← 完全等价，-> 就是"(*p)." 的简写。题目要求用这个
//
//   所以：
//      p->name   就是 p 指向的那个学生的姓名
//      p->id     就是 p 指向的那个学生的学号
//      p->score  就是 p 指向的那个学生的成绩
//
//   对比记忆：
//      Student s;   →  s.name      用「.」，因为 s 是对象本身
//      Student* p;  →  p->name     用「->」，因为 p 是"指向对象的指针"
//
// ============================================================
//
// 【自己动手填的部分】
//
//   在 input 里：把三个字段从键盘读进来
//       · 读姓名：用 std::cin >> ？        （提示：p->name 这个位置该怎么写）
//       · 读学号、读成绩同理
//       · 注意 id 是 int、score 是 float，cin 会自动转，不用特殊处理
//
//   在 display 里：按题目要求的格式输出三行
//       · 格式必须是  姓名：张三   （中文冒号，别写成英文的 :）
//       · 每行结尾加 "\n" 换行
//
// ============================================================

#include <iostream>

// ↓↓↓ 从这里开始写你的代码 ↓↓↓
struct Student {
    char name [50];
    int id;
    float score;
};
void input(Student* p) {
    std::cin >>p->name;
    std::cin >> p->id;
    std::cin >> p->score;
}
void display(Student* p) {
    std::cout << "姓名：" << p->name << '\n';
    std::cout << "学号：" << p->id << '\n';
    std::cout << "成绩：" << p->score << '\n';
}

// ↑↑↑ 到这里结束 ↑↑↑

int main() {
    Student* p = new Student;   // 动态创建
    input(p);
    display(p);
    delete p;                   // 释放
    return 0;// 提示：动态创建、调用两个函数、记得释放
}
              
